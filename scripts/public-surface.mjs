// The public surface the API Extractor reports do not see: the stylesheet's `cdt-*` class names, the `data-*`
// attributes its selectors key on and its layer order, plus each package's `exports` entry points, CLI names and
// CLI options.
// `check-api.mjs` writes these lists to committed baselines and fails when the build no longer matches, so a
// renamed or deleted class cannot ship without someone updating the baseline on purpose.

const CLASS = /\.(cdt-[A-Za-z0-9_-]+)/g;
const DATA_ATTRIBUTE = /\[(data-[a-z0-9-]+)/g;
const LAYER_ORDER = /@layer\s+([a-z0-9.,\s-]+);/;

const sorted = (values) => [...new Set(values)].sort();

/** Class names, `data-*` attribute names and the declared layer order of one built stylesheet. */
export function cssSurface(cssText) {
  const withoutComments = cssText.replace(/\/\*[\s\S]*?\*\//g, "");
  const layers = LAYER_ORDER.exec(withoutComments)?.[1].split(",").map((name) => name.trim()).filter(Boolean) ?? [];
  return {
    layers,
    classes: sorted([...withoutComments.matchAll(CLASS)].map((match) => match[1])),
    dataAttributes: sorted([...withoutComments.matchAll(DATA_ATTRIBUTE)].map((match) => match[1])),
  };
}

/** Entry points and CLI names one package manifest declares. */
export function packageSurface(manifest) {
  return {
    name: manifest.name,
    exports: sorted(Object.keys(manifest.exports ?? {})),
    bin: sorted(Object.keys(manifest.bin ?? {})),
  };
}

/**
 * The arguments one CLI accepts, read from the usage line it prints on a bad argument: each bracketed option
 * (`--out <dir>`) and each positional (`<path...>`) becomes one `cli argument` entry, so removing an option
 * shows as `-` and adding one as `+`.
 */
export function cliArguments(bin, usage) {
  const line = /usage:\s*(\S+)\s*(.*)/.exec(usage);
  if (line === null || line[1] !== bin) throw new Error(`${bin}: no usage line in its argument error output`);
  return [...line[2].matchAll(/\[([^\]]+)\]|(<[^>]+>)/g)].map((match) => `${bin} ${(match[1] ?? match[2]).trim()}`);
}

const section = (title, values) => [`## ${title}`, "", ...(values.length === 0 ? ["(none)"] : values), ""];

/** One stable plain-text report: same input, same bytes, so a diff of the baseline is the API change. */
export function renderSurface({ stylesheets, packages }) {
  const lines = ["# Conductor public surface (generated by `pnpm check:api --update`; do not edit)", ""];
  for (const { name, manifest, cliUsage = {} } of packages) {
    const surface = packageSurface(manifest);
    const options = surface.bin.flatMap((bin) => cliArguments(bin, cliUsage[bin] ?? ""));
    lines.push(...section(`${name} exports`, surface.exports), ...section(`${name} bin`, surface.bin), ...section(`${name} bin arguments`, options));
  }
  for (const { file, css } of stylesheets) {
    const surface = cssSurface(css);
    lines.push(...section(`${file} layer order`, surface.layers.length === 0 ? [] : [surface.layers.join(", ")]), ...section(`${file} classes`, surface.classes), ...section(`${file} data attributes`, surface.dataAttributes));
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Parses a report back into `section → values`, so drift is judged per stylesheet and per package. */
function parseSurface(report) {
  const sections = new Map();
  let current;
  for (const line of report.split("\n")) {
    if (line.startsWith("## ")) sections.set((current = line.slice(3)), new Set());
    else if (current !== undefined && line !== "" && line !== "(none)") sections.get(current).add(line);
  }
  return sections;
}

/** What the current build removed from and added to the baseline, as `section: value` entries. */
export function surfaceDiff(baseline, current) {
  const before = parseSurface(baseline);
  const after = parseSurface(current);
  const missing = (from, to) => [...from].flatMap(([title, values]) => [...values].filter((value) => !to.get(title)?.has(value)).map((value) => `${title}: ${value}`));
  return { removed: missing(before, after), added: missing(after, before) };
}
