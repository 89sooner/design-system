import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const source = `${root}/packages/tokens/dist/contrast-report.json`;
const target = fileURLToPath(new URL("../src/generated/contrast-report.ts", import.meta.url));
mkdirSync(fileURLToPath(new URL("../src/generated", import.meta.url)), { recursive: true });
const report = existsSync(source) ? readFileSync(source, "utf8").trimEnd() : "null";
if (report === "null") console.warn("[docs] contrast-report.json is unavailable; token reference will show 측정되지 않음.");
writeFileSync(target, `// Generated by build-contrast-report.mjs\nexport default ${report} as const;\n`);
