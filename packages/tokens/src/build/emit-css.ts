/**
 * CSS custom property emission.
 *
 * Only semantic and component tokens reach CSS: a primitive has no `--cdt-` name
 * (FR-TOK-004 AC-4). Values arrive fully resolved, so no `var()` chain survives
 * into the artifact (FR-TOK-003 AC-1).
 *
 * `emitCss` takes a list of themes. Dark is the only one today; WP-010 appends the light theme
 * without touching this signature.
 *
 * Refs: WP-003 FR-TOK-004 · WP-005 FR-TOK-009
 */
import { groupKeyOf } from "../schema";
import type { TokenDefinition } from "../schema";
import { assertNoBreakpointVarsInMedia, substituteBreakpoints } from "./media";
import { assertNoNameCollisions, assertPrefixed, cssPropertyName } from "./names";

export interface ThemeEmit {
  readonly theme: string;
  /** Selectors this theme's block applies to, in source order. */
  readonly selectors: readonly string[];
  readonly colorScheme: "dark" | "light";
  /** Resolved literal per emitted token key. */
  readonly values: ReadonlyMap<string, string>;
}

const BANNER = [
  "/*",
  " * Generated by @conductor/tokens. Do not edit.",
  " * Source: packages/tokens/src/{primitives,palette.dark,scales,components}.ts",
  " */",
].join("\n");

/** Tokens that own a CSS custom property. */
export function emittableTokens(tokens: readonly TokenDefinition[]): TokenDefinition[] {
  return tokens.filter((token) => token.tier !== "primitive");
}

function declarationsFor(
  tokens: readonly TokenDefinition[],
  values: ReadonlyMap<string, string>,
): string[] {
  const lines: string[] = [];
  let previousGroup: string | undefined;

  for (const token of tokens) {
    const group = groupKeyOf(token.key);
    if (previousGroup !== undefined && group !== previousGroup) lines.push("");
    previousGroup = group;

    // Emission order equals declaration order, so a rebuild is byte-identical.
    const resolved = values.get(token.key) as string;
    lines.push(`  ${cssPropertyName(token.key)}: ${resolved};`);
  }
  return lines;
}

export function emitCss(tokens: readonly TokenDefinition[], themes: readonly ThemeEmit[]): string {
  const emitted = emittableTokens(tokens);
  assertNoNameCollisions(emitted);
  assertPrefixed(emitted.map((token) => cssPropertyName(token.key)));

  const blocks = themes.map((theme) => {
    const selector = theme.selectors.join(",\n");
    const body = [`  color-scheme: ${theme.colorScheme};`, "", ...declarationsFor(emitted, theme.values)];
    return `${selector} {\n${body.join("\n")}\n}`;
  });

  const css = `${BANNER}\n\n${blocks.join("\n\n")}\n`;
  const substituted = substituteBreakpoints(css);
  assertNoBreakpointVarsInMedia(substituted);
  return substituted;
}
