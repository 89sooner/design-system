/**
 * TypeScript emission.
 *
 * `tokens` is a const-asserted nested object whose leaves are `var(--cdt-*)` strings, so
 * `tokens.surface.raised` infers the string literal `"var(--cdt-surface-raised)"`
 * (FR-TOK-006 AC-1) and `tokens.surface.nonexistent` does not typecheck (AC-2).
 *
 * The values are custom property references rather than raw colours on purpose
 * (`conductor_data_model.md` 5): a theme switch repaints through the cascade, so code holding
 * these constants never re-renders (FR-THM-003 AC-4).
 *
 * Refs: WP-004 FR-TOK-006 · WP-005 FR-TOK-009
 */
import type { TokenDefinition } from "../schema";
import { breakpointPixels } from "./media";
import { cssPropertyName, isSafeIdentifier } from "./names";

interface TokenNode {
  readonly children: Map<string, TokenNode>;
  leaf?: string;
}

function emptyNode(): TokenNode {
  return { children: new Map() };
}

/** Insertion order is declaration order, which keeps a rebuild byte-identical. */
function buildTree(tokens: readonly TokenDefinition[]): TokenNode {
  const root = emptyNode();

  for (const token of tokens) {
    let node = root;
    const segments = token.key.split(".");

    for (const segment of segments.slice(0, -1)) {
      let child = node.children.get(segment);
      if (!child) {
        child = emptyNode();
        node.children.set(segment, child);
      }
      node = child;
    }

    const last = segments[segments.length - 1] as string;
    let leafNode = node.children.get(last);
    if (!leafNode) {
      leafNode = emptyNode();
      node.children.set(last, leafNode);
    }
    leafNode.leaf = `var(${cssPropertyName(token.key)})`;
  }

  return root;
}

function propertyName(segment: string): string {
  return isSafeIdentifier(segment) ? segment : JSON.stringify(segment);
}

function serialize(node: TokenNode, depth: number): string {
  const pad = "  ".repeat(depth);
  const innerPad = "  ".repeat(depth + 1);

  const entries = [...node.children.entries()].map(([segment, child]) => {
    const name = propertyName(segment);
    if (child.leaf !== undefined && child.children.size === 0) {
      return `${innerPad}${name}: ${JSON.stringify(child.leaf)},`;
    }
    return `${innerPad}${name}: ${serialize(child, depth + 1)},`;
  });

  return `{\n${entries.join("\n")}\n${pad}}`;
}

const TOKENS_BANNER = [
  "/**",
  " * Generated by @conductor-by-89soone/tokens. Do not edit.",
  " * Run `pnpm --filter @conductor-by-89soone/tokens run build` to regenerate.",
  " *",
  " * Values are CSS custom property references, not raw colours: a theme swap changes what the",
  " * browser resolves them to, never the strings themselves (FR-THM-003 AC-4).",
  " */",
].join("\n");

/** The full text of `src/tokens.ts`. */
export function emitTokensModule(tokens: readonly TokenDefinition[]): string {
  const emitted = tokens.filter((token) => token.tier !== "primitive");
  const tree = buildTree(emitted);

  return [
    TOKENS_BANNER,
    "",
    `export const tokens = ${serialize(tree, 0)} as const;`,
    "",
    "/** Shape of the token object, with every leaf narrowed to its own string literal. */",
    "export type Tokens = typeof tokens;",
    "",
  ].join("\n");
}

const BREAKPOINTS_BANNER = [
  "/**",
  " * Generated by @conductor-by-89soone/tokens. Do not edit.",
  " * Run `pnpm --filter @conductor-by-89soone/tokens run build` to regenerate.",
  " *",
  " * Literal pixel numbers, unlike `tokens`: a custom property does not evaluate inside a media",
  " * query condition, so JS that computes a breakpoint needs the number itself (FR-TOK-009 AC-3).",
  " */",
].join("\n");

/** The full text of `src/breakpoints.ts`. */
export function emitBreakpointsModule(): string {
  const entries = Object.entries(breakpointPixels).map(
    ([name, pixels]) => `  ${propertyName(name)}: ${pixels},`,
  );

  return [
    BREAKPOINTS_BANNER,
    "",
    `export const breakpoints = {\n${entries.join("\n")}\n} as const;`,
    "",
    "/** Shape of the breakpoint object, with every value narrowed to its own numeric literal. */",
    "export type Breakpoints = typeof breakpoints;",
    "",
  ].join("\n");
}
